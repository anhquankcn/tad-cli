/**
 * Vietnamese overlay for TAD.
 *
 * Harness only ships `LOCALE_IDS = ['zh', 'en']` and its Settings schema rejects any
 * other id, so Vietnamese cannot be a real `LocaleId` without forking the Harness
 * `client-locale` package too. This overlay therefore sits *on top of* the English
 * output: `ui(zh, en)` and `translateUiText()` look the English string up here and
 * return the Vietnamese form when one exists.
 *
 * Consequences of that choice, on purpose:
 *   - Enabled with `SEEKTTY_LANG=vi`; Harness Settings still stores `en`.
 *   - A string missing from this map renders in English, never in Chinese, so
 *     translation can land incrementally without breaking the UI.
 *   - Keys must match the English text exactly, including trailing spaces,
 *     punctuation, and separators such as ` · `.
 *
 * Generated from every `ui(zh, en)` call site and the legacy `ENGLISH_TEXT` table.
 */

