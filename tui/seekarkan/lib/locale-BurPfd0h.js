function requestedEnvironmentLocale(env) {
	const candidates = [
		env.LC_ALL,
		env.LC_MESSAGES,
		...env.LANGUAGE?.split(":") ?? [],
		env.LANG
	];
	for (const candidate of candidates) {
		const normalized = candidate?.trim().toLowerCase();
		if (normalized === void 0 || normalized === "") continue;
		if (/^en(?:[-_.@]|$)/u.test(normalized)) return "en";
		if (/^zh(?:[-_.@]|$)/u.test(normalized)) return "zh";
	}
	return DEFAULT_TUI_LOCALE;
}
/** Resolve the pre-connection CLI language from POSIX locale variables. */
function localeFromEnvironment(env = process.env) {
	return requestedEnvironmentLocale(env);
}
function localeValue(document) {
	if (typeof document.value !== "object" || document.value === null || Array.isArray(document.value)) throw new Error("Harness locale Settings value must be an object");
	const preference = document.value[LOCALE_PREFERENCE_FIELD];
	if (preference === void 0) return {};
	if (!LOCALE_IDS.some((candidate) => candidate === preference)) throw new Error(`Harness locale preference is invalid: ${JSON.stringify(preference)}`);
	return { preference };
}
/** Read the current process-local terminal language. */
function uiLocale() {
	return currentLocale;
}
/** Change terminal presentation only; durable state remains in Harness Settings. */
function setUiLocale(locale) {
	if (!LOCALE_IDS.includes(locale)) throw new Error(`Unsupported locale ${JSON.stringify(locale)}`);
	if (currentLocale === locale) return false;
	currentLocale = locale;
	return true;
}
/** Select one of two authored UI strings at the point where presentation is built. */
function ui(zh, en) {
	if (VIETNAMESE_ENABLED) return toVietnamese(en);
	return currentLocale === "en" ? en : zh;
}
/** Translate a known legacy Chinese UI string without altering unknown model or provider content. */
function translateUiText(text) {
	if (text === "") return text;
	if (currentLocale === "zh" && !VIETNAMESE_ENABLED) return text;
	const exact = ENGLISH_TEXT.get(text);
	if (exact !== void 0) return toVietnamese(exact);
	for (const entry of ENGLISH_PATTERNS) {
		const match = entry.pattern.exec(text);
		if (match !== null) return toVietnamese(entry.replace(...match.slice(1)));
	}
	return text;
}
/** Find the official locale descriptor registered by the Harness plugin. */
function localeSettings(documents) {
	const document = documents.find((candidate) => candidate.namespace === LOCALE_SETTINGS_NAMESPACE);
	if (document === void 0) throw new Error(`Harness did not register Settings namespace ${LOCALE_SETTINGS_NAMESPACE}`);
	return document;
}
/** Read the persisted explicit choice, or `auto` when each client chooses its platform language. */
function languageSelection(document) {
	return localeValue(document).preference ?? "auto";
}
/** Resolve the terminal language from the shared preference and POSIX locale variables. */
function localeFromSettings(documents, env = process.env) {
	return localeValue(localeSettings(documents)).preference ?? localeFromEnvironment(env);
}
/** Persist an explicit or automatic language choice through the Harness Settings service. */
async function saveLanguage(settings, document, selection, env = process.env) {
	const updated = await settings.mutate(LOCALE_SETTINGS_NAMESPACE, selection === "auto" ? [{
		op: "unset",
		path: [LOCALE_PREFERENCE_FIELD]
	}] : [{
		op: "set",
		path: [LOCALE_PREFERENCE_FIELD],
		value: selection
	}], document.revision);
	const stored = languageSelection(updated);
	if (stored !== selection) throw new Error(`Harness stored an unexpected locale preference ${JSON.stringify(stored)}`);
	return {
		document: updated,
		locale: stored === "auto" ? localeFromEnvironment(env) : stored
	};
}

